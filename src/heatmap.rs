// ---------------------------------------------------------------------------
// Heatmap
// ---------------------------------------------------------------------------

pub fn make_heatmap_rgb(
    mz:    &[f32],
    mob:   &[f32],
    inten: &[f32],
) -> Vec<u8> {
    let mut grid = vec![0.0f32; MOB_BINS * MZ_BINS];

    for ((m, k), &i) in mz.iter().zip(mob.iter()).zip(inten.iter()) {
        if i <= 0.0 { continue; }
        let xi = ((*m  - MZ_MIN)  / (MZ_MAX  - MZ_MIN)  * MZ_BINS  as f32) as usize;
        let yi = ((*k  - MOB_MIN) / (MOB_MAX  - MOB_MIN) * MOB_BINS as f32) as usize;
        let xi = xi.min(MZ_BINS  - 1);
        let yi = yi.min(MOB_BINS - 1);
        let cell = &mut grid[yi * MZ_BINS + xi];
        if i > *cell { *cell = i; }
    }

    // Dilation: 2D max-pool with DILATE radius
    let dilated = max_pool_2d(&grid, MOB_BINS, MZ_BINS, DILATE);

    // Log-normalise
    let max_val = dilated.iter().cloned().fold(0.0f32, f32::max);
    if max_val <= 0.0 {
        return vec![0u8; MOB_BINS * MZ_BINS * 3];
    }
    let log_max = (max_val + 1.0).ln();

    // Build RGB, flip Y so low 1/K0 = bottom
    let mut rgb = vec![0u8; MOB_BINS * MZ_BINS * 3];
    for row in 0..MOB_BINS {
        let src_row = MOB_BINS - 1 - row;  // flip
        for col in 0..MZ_BINS {
            let v = dilated[src_row * MZ_BINS + col];
            if v <= 0.0 { continue; }   // stays black
            let t = ((v + 1.0).ln() / log_max * 255.0) as usize;
            let t = t.min(255);
            let dst = (row * MZ_BINS + col) * 3;
            rgb[dst]     = PLASMA_R[t];
            rgb[dst + 1] = PLASMA_G[t];
            rgb[dst + 2] = PLASMA_B[t];
        }
    }
    rgb
}

fn max_pool_2d(grid: &[f32], rows: usize, cols: usize, radius: usize) -> Vec<f32> {
    let mut out = vec![0.0f32; rows * cols];
    for r in 0..rows {
        let r0 = r.saturating_sub(radius);
        let r1 = (r + radius + 1).min(rows);
        for c in 0..cols {
            let c0 = c.saturating_sub(radius);
            let c1 = (c + radius + 1).min(cols);
            let mut mx = 0.0f32;
            for rr in r0..r1 {
                for cc in c0..c1 {
                    let v = grid[rr * cols + cc];
                    if v > mx { mx = v; }
                }
            }
            out[r * cols + c] = mx;
        }
    }
    out
}
